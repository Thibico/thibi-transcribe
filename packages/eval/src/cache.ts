import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

/**
 * The response cache — the thing that makes a second run free.
 *
 * A 107-language sweep is expensive once and should be free forever after, because the
 * inputs are deterministic: the same clip, the same provider, the same parameters. That is
 * also what makes `thibi eval report --run <id>` reproducible with the network off, which
 * §5 requires so a disputed number can be re-derived by someone who was not there.
 *
 * The key is `sha256(provider|model|lang|clipHash|paramsHash)`. Every component is load
 * bearing, and `paramsHash` is the one that has to be got right: it must cover everything
 * that could change the response and nothing that could not. For the LLM evals it **must**
 * include `promptId` and `promptVersion` — that single line is what makes a bumped prompt a
 * genuine cache miss, and it is the only thing stopping the CI gate from passing on numbers
 * generated by the previous prompt.
 */

/**
 * Stable JSON: object keys sorted at every depth, arrays left in order.
 *
 * `JSON.stringify` preserves insertion order, so `{a:1,b:2}` and `{b:2,a:1}` — the same
 * params, built by two call sites — would hash differently and split the cache in half
 * without anything looking wrong.
 */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value) ?? 'null';
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
}

const sha256 = (input: string | Buffer) => createHash('sha256').update(input).digest('hex');

export interface ResponseKeyInput {
  provider: string;
  model: string;
  lang: string;
  clipHash: string;
  paramsHash: string;
}

export function responseKey(i: ResponseKeyInput): string {
  return sha256([i.provider, i.model, i.lang, i.clipHash, i.paramsHash].join('|'));
}

/** Audio: sha256 of the wav bytes, so a re-download or a manifest copy is still a hit. */
export const clipHashOf = (bytes: Buffer): string => `sha256:${sha256(bytes)}`;

/** Text, for the LLM evals: sha256 of the exact input string. */
export const textHashOf = (s: string): string => `sha256:${sha256(Buffer.from(s, 'utf8'))}`;

export const paramsHashOf = (params: unknown): string =>
  sha256(Buffer.from(canonicalJson(params), 'utf8'));

export interface CachedResponse<T = unknown> {
  key: string;
  storedAt: string;
  value: T;
}

/**
 * File-backed, one JSON document per key at `<cacheDir>/resp/<key>.json`.
 *
 * `--no-cache` bypasses **reads but still writes**, which is deliberate and worth stating:
 * the flag exists to force fresh provider responses, not to throw them away afterwards. A
 * run that refetches and then discards would make the next run expensive too, and nobody
 * passing `--no-cache` wants that.
 */
export class ResponseCache {
  constructor(
    private readonly dir: string,
    private readonly options: { read?: boolean } = {},
  ) {}

  private pathFor(key: string): string {
    // Two-character shard: a 107-language sweep at n=30 is ~3200 files, and flat directories
    // that size are slow to list on every filesystem anyone will run this on.
    return join(this.dir, 'resp', key.slice(0, 2), `${key}.json`);
  }

  async get<T>(key: string): Promise<T | null> {
    if (this.options.read === false) return null;
    try {
      const raw = await readFile(this.pathFor(key), 'utf8');
      return (JSON.parse(raw) as CachedResponse<T>).value;
    } catch {
      return null;
    }
  }

  async set<T>(key: string, value: T, now: Date): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    const doc: CachedResponse<T> = { key, storedAt: now.toISOString(), value };
    await writeFile(path, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
  }
}
